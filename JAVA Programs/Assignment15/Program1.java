// Create Static Array with hardcoded values and display using built-in methods.

import java.util.*;

class Program1
{

    public static void main(String args[])
    {
        try
        {
            int iArr[]= {10,20,30,40,50};
            //built-in to display elements
            System.out.println("Array elements are: "+Arrays.toString(iArr));
        }
        catch(Exception eObj)
        {
            System.out.println(eObj);
        }
    }
}

